/* =============================================================================
   config.js — ВСЕ НАСТРОЙКИ ИГРЫ В ОДНОМ МЕСТЕ
   -----------------------------------------------------------------------------
   Зачем отдельный файл под числа?
   Это приём называется "вынести магические числа в конфиг". Если раскидать
   числа (силу броска, гравитацию, прочность досок) по всему коду, то потом
   невозможно ничего настроить: надо искать их по всем файлам.
   А так — открыл config.js, покрутил одно число, обновил страницу, смотришь.
   ============================================================================= */

