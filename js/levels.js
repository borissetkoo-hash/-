/* =============================================================================
   levels.js — ОПИСАНИЕ УРОВНЕЙ (ДАННЫЕ, А НЕ КОД)
   -----------------------------------------------------------------------------
   Уровень это просто список объектов: где стоит доска, где сидит свинья.
   Принцип: ДАННЫЕ ОТДЕЛЬНО, КОД ОТДЕЛЬНО. Чтобы сделать новый уровень, движок
   игры трогать не надо.

   ПОЧЕМУ ЗДЕСЬ ФУНКЦИИ-ПОМОЩНИКИ, А НЕ ГОЛЫЕ ЧИСЛА
   Первая версия этого файла была написана числами вручную. Проверка
   tools/check-levels.js нашла в ней 29 ошибок: доски пересекались друг с другом
   на 3-4 пикселя, свиньи висели в воздухе. Физический движок такие пересечения
   разруливает резким расталкиванием, и конструкция разваливалась сама, без
   единого выстрела.

   Причина ошибок была всегда одна: я считал высоты в уме и путался, потому что
   у Matter.js координата это ЦЕНТР тела, а думать удобнее про поверхность.

   Поэтому ниже заведены функции put*, которые работают в понятиях
   "поверхность": ты говоришь "поставь стойки высотой 110 на эту поверхность",
   а функция сама считает центр и ВОЗВРАЩАЕТ НОВУЮ ПОВЕРХНОСТЬ сверху. Дальше
   строишь следующий этаж от неё. Числа в уме больше не считаются нигде, и
   целый класс ошибок просто исчезает.

   Это общий приём: если ты постоянно ошибаешься в одном и том же вычислении,
   не будь внимательнее — спрячь вычисление в функцию.
   ============================================================================= */

const GY = CONFIG.ground.y;   // уровень земли, 780
const T  = 18;                // стандартная толщина доски

/* --- НИЗКОУРОВНЕВЫЕ СОЗДАТЕЛИ --------------------------------------------- */
const b = (x, y, w, h, material, angle = 0) => ({ x, y, w, h, material, angle });
const p = (x, y, radius, kind = 'normal') => ({ x, y, radius, kind });

/* --- ПОМОЩНИКИ, МЫСЛЯЩИЕ "ПОВЕРХНОСТЯМИ" ----------------------------------
   Каждый принимает surface — высоту поверхности, НА которую ставим,
   и возвращает высоту новой поверхности СВЕРХУ поставленного.
   Это позволяет писать строительство в одну цепочку сверху вниз по тексту,
   а по смыслу снизу вверх. */

// Поставить ряд вертикальных стоек
function putColumns(out, xs, surface, height, material, width = T) {
  for (const x of xs) out.blocks.push(b(x, surface - height / 2, width, height, material));
  return surface - height;
}

// Положить горизонтальную балку
function putBeam(out, x, surface, width, material, thickness = T) {
  out.blocks.push(b(x, surface - thickness / 2, width, thickness, material));
  return surface - thickness;
}

// Поставить квадратный ящик
function putBox(out, x, surface, size, material) {
  out.blocks.push(b(x, surface - size / 2, size, size, material));
  return surface - size;
}

// Посадить свинью
function putPig(out, x, surface, radius, kind = 'normal') {
  out.pigs.push(p(x, surface - radius, radius, kind));
}

/* КРЫША ДОМИКОМ ИЗ ДВУХ НАКЛОННЫХ ДОСОК
   -----------------------------------------------------------------------------
   Сначала я поставил два наклонных ската по отдельности, далеко друг от друга.
   В игре они немедленно упали плашмя — и это правильная физика: одиночная
   наклонная доска ни на что не опирается, ей не на чем стоять.

   Чтобы крыша держалась, скаты должны УПИРАТЬСЯ ДРУГ В ДРУГА вверху. Тогда
   каждый не даёт упасть другому, и конструкция стоит сама. Это называется
   распор: ровно так держатся карточный домик и каменная арка.

   ГЕОМЕТРИЯ. Доска длины L, повёрнутая на угол a, тянется от центра в обе
   стороны на вектор (L/2 * cos a, L/2 * sin a). Значит:
     - по горизонтали её конец отстоит от центра на  dx = |L/2 * cos a|
     - вниз она выступает на  |L/2 * sin a| + |толщина/2 * cos a|
       (второе слагаемое — вклад толщины самой доски)

   Чтобы верхние концы встретились в точке apexX, центры ставим на apexX -+ dx.
   Угол у левого ската отрицательный, у правого положительный: они зеркальны. */
function putRoof(out, apexX, surface, length, angle, material, thickness = T, gap = 16) {
  const half = length / 2;
  const dx = Math.abs(half * Math.cos(angle)) + gap / 2;
  const halfDown = Math.abs(half * Math.sin(angle)) +
                   Math.abs((thickness / 2) * Math.cos(angle));
  const cy = surface - halfDown;

  out.blocks.push(b(apexX - dx, cy, length, thickness, material, -angle));
  out.blocks.push(b(apexX + dx, cy, length, thickness, material,  angle));

  /* УПОРЫ ПОД НИЖНИМИ КОНЦАМИ.
     Одного распора вверху мало. Наклонная доска давит на опору не только вниз,
     но и НАРУЖУ, в сторону. Пока этой боковой силы меньше, чем сила трения,
     всё стоит. Как только больше — ноги разъезжаются, и крыша складывается.
     Именно это и происходило в тесте: скаты съезжали с 60 градусов до 15.

     Поэтому под нижние концы ставятся упоры — короткие тяжёлые камни. В
     настоящей стропильной крыше ровно та же деталь и та же задача: принять
     боковой распор, чтобы стены не разъехались.

     footX — расстояние от конька до самой внешней точки ската внизу. Считается,
     а не подбирается на глаз: половина длины вдоль наклона плюс вклад толщины. */
  const footX = dx + Math.abs(half * Math.cos(angle)) +
                Math.abs((thickness / 2) * Math.sin(angle));
  const cw = 28, ch = 24;
  out.blocks.push(b(apexX - footX - cw / 2 - 1, surface - ch / 2, cw, ch, 'stone'));
  out.blocks.push(b(apexX + footX + cw / 2 + 1, surface - ch / 2, cw, ch, 'stone'));
}

/* Сдвинуть готовую постройку целиком по горизонтали.

   Зачем: сначала удобно спроектировать крепость вокруг круглых координат вроде
   1300, а потом одним числом подобрать, на каком расстоянии от рогатки она
   стоит. Именно так работают редакторы уровней: объект собирают как заготовку,
   а потом целиком ставят в нужное место.

   Альтернатива — переписать тридцать чисел руками при каждой правке дистанции.
   Так делать не надо. */
function moveAll(out, dx) {
  for (const block of out.blocks) block.x += dx;
  for (const pig of out.pigs) pig.x += dx;
  return out;
}

/* Насколько близко к рогатке стоят все постройки. Одно число на всю игру:
   уменьшишь — крепости отъедут дальше и стрелять станет труднее. */
const FORT_OFFSET = -280;

/* =============================================================================
   УРОВЕНЬ 1 — ДЕРЕВЯННАЯ ЗАСТАВА
   Собран по твоему первому скриншоту: трёхэтажная деревянная постройка,
   свиньи внутри, король и ящик динамита на крыше, ледяной сарай сбоку.
   ============================================================================= */
function level1() {
  const out = { blocks: [], pigs: [] };

  // --- Первый этаж ---
  const s1 = putColumns(out, [1150, 1290, 1430, 1570], GY, 110, 'wood');
  putPig(out, 1220, GY, 20);
  putPig(out, 1360, GY, 20);
  putPig(out, 1500, GY, 20);

  // Два перекрытия, каждое лежит на двух стойках
  putBeam(out, 1240, s1, 220, 'wood');
  const s2 = putBeam(out, 1480, s1, 220, 'wood');

  // --- Второй этаж ---
  const s3 = putColumns(out, [1200, 1330, 1480], s2, 90, 'wood');
  putPig(out, 1262, s2, 17);
  putPig(out, 1405, s2, 17);

  // Одна длинная балка на все три стойки — так устойчивее, чем две короткие
  const s4 = putBeam(out, 1340, s3, 300, 'wood');

  // --- Башенка с королём ---
  const s5 = putColumns(out, [1290, 1390], s4, 70, 'wood');
  const s6 = putBeam(out, 1340, s5, 150, 'wood');
  putPig(out, 1300, s6, 22, 'king');
  putBox(out, 1390, s6, 36, 'tnt');

  // --- Ледяной сарай справа ---
  const i1 = putColumns(out, [1650, 1760], GY, 100, 'ice');
  const i2 = putBeam(out, 1705, i1, 140, 'ice');
  putPig(out, 1705, i2, 18);

  moveAll(out, FORT_OFFSET);

  return {
    name: 'Деревянная застава',
    theme: 'day',
    birds: ['red', 'red', 'yellow', 'blue', 'black'],
    blocks: out.blocks,
    pigs: out.pigs
  };
}

/* =============================================================================
   УРОВЕНЬ 2 — КАМЕННЫЙ ФОРТ
   Главная мысль уровня: камень в лоб не пробить, зато ледяной фундамент
   хрупкий. Выбей опоры — и тяжёлые плиты обрушатся сами, раздавив всё внизу.
   Это и есть суть Angry Birds: не колотить по стенам, а искать слабое место.
   ============================================================================= */
function level2() {
  const out = { blocks: [], pigs: [] };

  // --- Хрупкий ледяной фундамент: вот сюда и надо целиться ---
  const s1 = putColumns(out, [1180, 1320, 1460, 1600], GY, 100, 'ice', 24);
  putPig(out, 1250, GY, 22);
  putPig(out, 1390, GY, 22);
  putPig(out, 1530, GY, 22);

  // --- Тяжёлые каменные плиты сверху ---
  putBeam(out, 1250, s1, 200, 'stone', 26);
  const s2 = putBeam(out, 1530, s1, 200, 'stone', 26);

  // --- Деревянный второй этаж ---
  const s3 = putColumns(out, [1250, 1530], s2, 100, 'wood');
  putPig(out, 1310, s2, 19);
  putPig(out, 1470, s2, 19);

  const s4 = putBeam(out, 1390, s3, 320, 'wood');

  // --- Крыша: каменный парапет, динамит и король ---
  putBox(out, 1270, s4, 44, 'stone');
  putBox(out, 1510, s4, 44, 'stone');
  putBox(out, 1390, s4, 36, 'tnt');
  putPig(out, 1330, s4, 24, 'king');

  moveAll(out, FORT_OFFSET);

  return {
    name: 'Каменный форт',
    theme: 'day',
    birds: ['red', 'yellow', 'yellow', 'black', 'blue'],
    blocks: out.blocks,
    pigs: out.pigs
  };
}

/* =============================================================================
   УРОВЕНЬ 3 — ВУЛКАН
   По второму скриншоту: тёмная тема, длинный мост, наклонная крыша,
   динамит под мостом. Ледяная колонна посередине держит мост: выбьешь её —
   мост просядет вместе со всем, что на нём стоит.
   Углы задаются в РАДИАНАХ: Math.PI / 6 это 30 градусов.
   ============================================================================= */
function level3() {
  const out = { blocks: [], pigs: [] };

  // --- Две каменные опорные башни ---
  const t1 = putColumns(out, [1130, 1210], GY, 120, 'stone', 24);
  putColumns(out, [1560, 1640], GY, 120, 'stone', 24);

  // Свиньи-наблюдатели на крайних башнях (сдвинуты так, чтобы не задеть мост)
  putPig(out, 1125, t1, 18);
  putPig(out, 1645, t1, 18);

  // --- Ледяная колонна по центру: подпирает мост снизу ---
  const ic = putColumns(out, [1385], GY, 100, 'ice', 26);
  const it = putBeam(out, 1385, ic, 120, 'ice', 20);

  // --- Мост. Лежит на внутренних каменных башнях и на ледяной колонне ---
  const bridge = putBeam(out, 1385, it, 480, 'wood', 24);

  // --- Крыша домиком: два ската упираются друг в друга над королём ---
  /* Угол 60 градусов, а не 30. Пологая крыша в 30 градусов в игре расползалась:
     скаты съезжали по мосту наружу, потому что чем положе доска, тем сильнее
     она давит В СТОРОНЫ, а не вниз, и трения перестаёт хватать.
     Крутая крыша давит в основном вниз и стоит спокойно. */
  putRoof(out, 1385, bridge, 190, Math.PI / 3, 'wood');
  putPig(out, 1385, bridge, 24, 'king');

  // --- Динамит на земле под мостом ---
  putBox(out, 1320, GY, 40, 'tnt');
  putBox(out, 1450, GY, 40, 'tnt');

  // --- Свиньи в касках на земле ---
  putPig(out, 1260, GY, 20);
  putPig(out, 1510, GY, 20);

  moveAll(out, FORT_OFFSET);

  return {
    name: 'Вулкан',
    theme: 'volcano',
    birds: ['black', 'yellow', 'blue', 'red', 'black'],
    blocks: out.blocks,
    pigs: out.pigs
  };
}

