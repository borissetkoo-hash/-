/* =============================================================================
   УРОВЕНЬ 3 — ВУЛКАН
   По второму скриншоту: тёмная тема, длинный мост, наклонная крыша,
   динамит под мостом. Ледяная колонна посередине держит мост: выбьешь её —
   мост просядет вместе со всем, что на нём стоит.
   Углы задаются в РАДИАНАХ: Math.PI / 6 это 30 градусов.
   ============================================================================= */
function level3() {
  const out = { blocks: [], pigs: [], terrain: [] };

  // --- Две каменные опорные башни ---
  const t1 = putColumns(out, [1130, 1210], GY, 120, 'stone', 24);
  putColumns(out, [1560, 1640], GY, 120, 'stone', 24);

  // Свиньи-наблюдатели на крайних башнях (сдвинуты так, чтобы не задеть мост)
  putPig(out, 1125, t1, 18);
  putPig(out, 1645, t1, 18);

  // --- Ледяная колонна по центру: подпирает мост снизу ---
  const ic = putColumns(out, [1385], GY, 100, 'ice', 26);
  const it = putBeam(out, 1385, ic, 120, 'ice', 20);

  // --- Мост. Лежит на внутренних каменных башнях и на ледяной колонне ---
  const bridge = putBeam(out, 1385, it, 480, 'wood', 24);

  // --- Крыша домиком: два ската упираются друг в друга над королём ---
  /* Угол 60 градусов, а не 30. Пологая крыша в 30 градусов в игре расползалась:
     скаты съезжали по мосту наружу, потому что чем положе доска, тем сильнее
     она давит В СТОРОНЫ, а не вниз, и трения перестаёт хватать.
     Крутая крыша давит в основном вниз и стоит спокойно. */
  putRoof(out, 1385, bridge, 190, Math.PI / 3, 'wood');
  putPig(out, 1385, bridge, 24, 'king');

  // --- Динамит на земле под мостом ---
  putBox(out, 1320, GY, 40, 'tnt');
  putBox(out, 1450, GY, 40, 'tnt');

  // --- Свиньи в касках на земле ---
  putPig(out, 1260, GY, 20);
  putPig(out, 1510, GY, 20);

  moveAll(out, FORT_OFFSET);

  return {
    name: 'Вулкан',
    theme: 'volcano',
    birds: ['black', 'yellow', 'white', 'blue', 'red', 'black'],
    blocks: out.blocks,
    pigs: out.pigs,
    terrain: out.terrain
  };
}

/* =============================================================================
   УРОВЕНЬ 4 — КАМЕННЫЙ НАВЕС
   -----------------------------------------------------------------------------
   Идея уровня: свиней НЕЛЬЗЯ достать прямым выстрелом. Они сидят под тяжёлой
   каменной плитой, и сколько ни бей в лоб, попадёшь только в навес.

   Решений три, и все они честные:
     1. яйцо белой птицы падает отвесно и проходит в щель сверху,
     2. синяя делится на три и накрывает площадь,
     3. выбить ледяные опоры слева — тогда навес рухнет и раздавит свиней сам.
   Третий вариант самый дешёвый, и найти его и есть задача игрока.

   Зачем такой уровень: раньше способности можно было не использовать вообще.
   Здесь без них не обойтись, и они перестают быть украшением.
   ============================================================================= */
function level4() {
  const out = { blocks: [], pigs: [], terrain: [] };

  /* Вся крепость стоит на земляном плато. Это не украшение: теперь настильный
     выстрел врезается в торец плато и не долетает вовсе, и приходится брать
     выше. Высота плато прямо переводится в сложность прицеливания. */
  const ground = putPlatform(out, 1425, 720, GY - 80);

  // --- Опоры навеса. Слева лёд, справа камень: асимметрия и есть подсказка ---
  const left  = putColumns(out, [1150, 1230], ground, 120, 'ice', 24);
  putColumns(out, [1620, 1700], ground, 120, 'stone', 24);

  // --- Свиньи под навесом: прямым попаданием их не достать ---
  putPig(out, 1330, ground, 20);
  putPig(out, 1425, ground, 20);
  putPig(out, 1520, ground, 20);

  // --- Сам навес: длинная тяжёлая плита ---
  const roofTop = putBeam(out, 1425, left, 620, 'stone', 30);

  // --- На навесе домик короля и ящик динамита ---
  putPig(out, 1290, roofTop, 17);
  const hut = putColumns(out, [1360, 1490], roofTop, 80, 'wood');
  const hutTop = putBeam(out, 1425, hut, 190, 'wood');
  putPig(out, 1425, hutTop, 24, 'king');
  putBox(out, 1580, roofTop, 36, 'tnt');

  // --- Одна свинья снаружи, ВНИЗУ под обрывом: её достать проще всего ---
  putPig(out, 1720, GY, 18);

  moveAll(out, FORT_OFFSET);

  return {
    name: 'Каменный навес',
    theme: 'day',
    birds: ['white', 'blue', 'yellow', 'black', 'red'],
    blocks: out.blocks,
    pigs: out.pigs,
    terrain: out.terrain
  };
}

/* =============================================================================
   УРОВЕНЬ 5 — ЛЕДНИК
   -----------------------------------------------------------------------------
   Идея уровня: всё держится на льду, а сверху лежит камень.

   Лёд бьётся от любого попадания, но пока он цел, он держит вес. Стоит выбить
   одну колонну — и каменная плита, которая на ней лежала, падает вниз, прямо
   на свинью под башней. Погибнет она не от удара птицы, а от придавливания.

   Это тот самый расчёт по силе, который добавлялся отдельно: удар и завал —
   разные вещи, и здесь уровень построен вокруг второго.

   Три башни связаны деревянными мостками, поэтому падение одной раскачивает
   соседние. Один точный выстрел может увести весь ледник целиком.
   ============================================================================= */
function level5() {
  const out = { blocks: [], pigs: [], terrain: [] };

  // --- Три ледяные башни одинаковой высоты ---
  const ice = putColumns(out, [1150, 1240, 1380, 1470, 1610, 1700], GY, 90, 'ice', 26);

  // --- Свиньи ПОД башнями: их задавит упавшая плита ---
  putPig(out, 1195, GY, 20);
  putPig(out, 1425, GY, 20);
  putPig(out, 1655, GY, 20);

  // --- Каменные плиты, по одной на каждую пару колонн ---
  putBeam(out, 1195, ice, 160, 'stone', 26);
  putBeam(out, 1425, ice, 160, 'stone', 26);
  const top = putBeam(out, 1655, ice, 160, 'stone', 26);

  // --- Деревянные мостки между плитами: связывают башни в одну конструкцию ---
  putBeam(out, 1310, top, 110, 'wood');
  putBeam(out, 1540, top, 110, 'wood');

  // --- Свиньи наверху ---
  putPig(out, 1195, top, 18);
  putPig(out, 1400, top, 22, 'king');
  putBox(out, 1455, top, 36, 'tnt');
  putPig(out, 1655, top, 18);

  moveAll(out, FORT_OFFSET);

  return {
    name: 'Ледник',
    theme: 'winter',
    birds: ['yellow', 'blue', 'blue', 'black', 'red'],
    blocks: out.blocks,
    pigs: out.pigs,
    terrain: out.terrain
  };
}

/* =============================================================================
   УРОВЕНЬ 6 — ОБРЫВ
   -----------------------------------------------------------------------------
   Уровень целиком про рельеф. Два плато разной высоты, между ними провал.

   Что это меняет:
     - низкий выстрел бьётся о торец ближнего плато, надо брать навесом;
     - дальнее плато выше ближнего, поэтому одной настройки прицела на оба
       не хватает: каждый выстрел считается заново;
     - всё, что сваливается в провал, летит до самой земли, а падение с такой
       высоты убивает само по себе, без всякой птицы.

   Провал между плато шириной девяносто пикселей: достаточно, чтобы в него
   проваливались доски и свиньи, и недостаточно, чтобы туда можно было целиться
   специально. Он работает как ловушка, а не как мишень.
   ============================================================================= */
function level6() {
  const out = { blocks: [], pigs: [], terrain: [] };

  // --- Ближнее плато, пониже ---
  const near = putPlatform(out, 1250, 360, GY - 80);

  const n1 = putColumns(out, [1130, 1250, 1370], near, 90, 'wood');
  putPig(out, 1190, near, 18);
  putPig(out, 1310, near, 18);

  const n2 = putBeam(out, 1250, n1, 300, 'wood');
  putPig(out, 1140, n2, 17);
  putBox(out, 1370, n2, 36, 'tnt');

  const n3 = putColumns(out, [1190, 1310], n2, 70, 'wood');
  const n4 = putBeam(out, 1250, n3, 170, 'wood');
  putPig(out, 1250, n4, 22, 'king');

  // --- Провал: между 1430 и 1520 земли нет вообще ---

  // --- Дальнее плато, повыше и каменное ---
  const far = putPlatform(out, 1640, 240, GY - 130);

  const f1 = putColumns(out, [1560, 1720], far, 80, 'stone', 22);
  putPig(out, 1640, far, 20);

  const f2 = putBeam(out, 1640, f1, 220, 'stone', 26);
  putBox(out, 1580, f2, 36, 'tnt');
  putPig(out, 1690, f2, 18);

  moveAll(out, FORT_OFFSET);

  return {
    name: 'Обрыв',
    theme: 'day',
    birds: ['red', 'yellow', 'blue', 'black', 'white'],
    blocks: out.blocks,
    pigs: out.pigs,
    terrain: out.terrain
  };
}

